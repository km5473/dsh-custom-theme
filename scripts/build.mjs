import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
// Concatenated in dependency order; imports are dropped because the factory
// body is one scope and every declaration lands top-level there.
const sources=['palette.js','config.js','controller.js','image-store.js','art.js','glass.js','ai-palette.js','client.js'].map(name => fs.readFileSync(path.join(root,'src',name),'utf8').replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,''));
const css=fs.readFileSync(path.join(root,'src/card.css'),'utf8');
const read=name=>'data:image/webp;base64,'+fs.readFileSync(path.join(root,'assets',name+'.webp')).toString('base64');
// Only the artwork the client actually reads is bundled: the wallpaper plus the
// six standalone stickers. The sprite sheet is a settings-only convenience and
// would add ~2 MB to every page load.
const assets={ wallpaper:read('wallpaper') };
assets.individual=Array.from({length:6},(_,i)=>read(`sticker-${i}`));
// The module id must equal the id the Host knows the entry by. Staging a build
// under a previous name (so a session already running under it stays themed
// across a rename) is a build option, never an edit: the default always matches
// package.json.
const moduleId=process.argv[2]??pkg.name;
const outFile=process.argv[3]??path.join(root,'lib/client.js');
const code=`// Generated by scripts/build.mjs. DSH lazy factory; no runtime dependencies.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(moduleId)},factory:(require)=>{\n'use strict';\nconst React=require('react');\nconst ASSETS=${JSON.stringify(assets)};\n${sources.join('\n')}\nreturn {inject,apply:ctx=>applyClient(ctx,React,${JSON.stringify(css)},ASSETS)};\n}});\n`;
fs.mkdirSync(path.dirname(outFile),{recursive:true});
fs.writeFileSync(outFile,code);
console.log(`Built ${path.relative(root,outFile)} (id=${moduleId}, ${(Buffer.byteLength(code)/1048576).toFixed(2)} MB, ${assets.individual.length} stickers)`);
